#pragma once
#include <stdint.h>
#include <string.h>
// Native OpenConsole dispatcher identified in both slices of the supplied
// Open 1.3.7 custom binary. UUID and instruction bytes must both match.
typedef struct { uint32_t subtype; uint8_t uuid[16]; uintptr_t address; uint8_t code[20]; } NFBConsoleTarget;
static inline const NFBConsoleTarget *NFBConsoleTargetForImage(uint32_t cpu, uint32_t subtype, const uint8_t *uuid) {
    static const NFBConsoleTarget targets[] = {
    {0, {0x6f,0xea,0xd8,0x04,0xf1,0xc9,0x33,0x60,0xb3,0x5e,0xed,0xeb,0x38,0x63,0x20,0xfb}, 0x7aa24, {0x40,0x09,0x00,0xd0,0x00,0xe4,0x41,0xf9,0x41,0x09,0x00,0xf0,0x21,0xe0,0x01,0x91,0xb7,0xbf,0x03,0x14}},
    {2, {0x3a,0x86,0xa9,0x83,0xe7,0x81,0x3d,0x47,0xa5,0x99,0xa8,0x14,0x88,0xb1,0xe9,0x07}, 0x7d540, {0x80,0x09,0x00,0xf0,0x00,0xfc,0x42,0xf9,0xa1,0x09,0x00,0x90,0x21,0x40,0x02,0x91,0x1b,0xec,0x03,0x14}}
    };
    if (cpu != 0x0100000c || !uuid) return NULL;
    for (unsigned int index = 0; index < sizeof(targets)/sizeof(targets[0]); index++)
        if ((subtype & 0x00ffffff) == targets[index].subtype && !memcmp(uuid, targets[index].uuid,16)) return &targets[index];
    return NULL;
}
static inline int NFBConsoleCodeMatches(const NFBConsoleTarget *target, const void *code) {
    return target && code && !memcmp(target->code,code,sizeof(target->code));
}
